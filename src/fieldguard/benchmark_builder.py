@dataclass
class BenchmarkClaimRecord:
    """Complete schema for an annotated numerical claim in the FieldGuard benchmark."""

    claim_id: str
    question: str
    candidate_claim: str
    claimed_value: float | None
    claimed_unit: str | None
    numeric_operator: str | None
    scheme: str | None
    crop_category: str | None
    season: str | None
    geography: str | None
    qualification: str | None
    requested_policy_version: str | None
    requested_effective_date: str | None
    claim_type: str
    gold_verdict: str
    gold_evidence_ids: list[str]
    gold_rationale: str
    case_origin: str
    annotation_status: str
    annotator_notes: str
    claim_family_id: str
    split: str
    rule_parameter: str | None = None
    perturbation_dimension: str = "none"
    evidence_regime: str = "clean"
    temporal_category: str = "guidelines_2023"
    simulate_omitted_gold_in_retrieval: bool = False
    forced_retrieved_evidence_ids: list[str] | None = None

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


