def build_default_evidence_store(project_root: Path | None = None) -> EvidenceStore:
    """
    Load extracted corpus units from data/processed/ and populate a validated
    EvidenceStore with canonical structured rules.
    Also attempts to register the untrusted pilot memo rule in non-strict mode
    to record its rejection in store.rejected_rules.
    """
    if project_root is None:
        project_root = Path(__file__).resolve().parents[2]

    manifest = load_source_manifest(project_root / "data" / "manifests" / "source_manifest.json")
    units = load_extracted_corpus(project_root)

    store = EvidenceStore()
    for doc in manifest.documents:
        store.known_document_ids.add(doc.document_id)
    for u in units:
        store.register_evidence_unit(u)

    for rule in _build_canonical_structured_rules():
        store.add_structured_rule(rule, strict=True)

    # Attempt to register the unverified draft rule in non-strict mode so it is rejected and audited
    untrusted_candidate = StructuredRuleRecord(
        rule_id="RULE_UNVERIFIED_DRAFT_SPICE_2PCT",
        evidence_id="EV_DOC_UNVERIFIED_PILOT_MEMO_P1_CHUNK_1",
        scheme="PMFBY",
        rule_parameter="farmer_premium_rate",
        season="kharif",
        crop_category="commercial_and_horticultural",
        geography="all_india",
        minimum_value=None,
        maximum_rate=3.5,
        allowed_values=None,
        numeric_operator="le",
        unit="percent",
        basis="sum_insured",
        qualifier="unverified_working_group_proposal",
        requires_qualifier_for_unconditional_claim=True,
        source_document_id="DOC_UNVERIFIED_PILOT_MEMO",
        document_version="unverified_draft_v0",
        policy_era="unverified_draft",
        publication_date=None,
        section="Draft Note Section 1 (Unverified)",
        physical_pdf_page=1,
        printed_page="1",
        table_id=None,
        row_id=None,
        effective_from=None,
        effective_to=None,
        verification_status="unverified_source",
    )
    store.add_structured_rule(untrusted_candidate, strict=False)

    return store


def export_benchmark_evidence_jsonl(
    store: EvidenceStore,
    output_path: Path,
) -> None:
    """Export all corpus evidence units along with their linked structured rules to evidence.jsonl."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w", encoding="utf-8") as f:
        for ev_id, unit in store.evidence_units.items():
            d = unit.to_dict()
            linked_rules = [r.to_dict() for r in store.get_rules_for_evidence(ev_id)]
            d["structured_rules"] = linked_rules
            f.write(json.dumps(d, ensure_ascii=False) + "\n")
