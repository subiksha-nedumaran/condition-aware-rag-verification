class EvidenceStore:
    """
    Repository of extracted evidence units and verified structured numerical rules.
    Enforces strict provenance checks, rejects unverified or malformed records from
    the trusted rule store, and flags conflicts between official sources.
    """

    def __init__(self) -> None:
        self.evidence_units: dict[str, ExtractedEvidenceUnit] = {}
        self.trusted_rules: dict[str, StructuredRuleRecord] = {}
        self.rejected_rules: list[dict[str, Any]] = []
        self.evidence_to_rules: dict[str, list[StructuredRuleRecord]] = {}
        self.known_document_ids: set[str] = set()

    def register_evidence_unit(self, unit: ExtractedEvidenceUnit) -> None:
        if not unit.evidence_id or not unit.document_id:
            raise ValueError("Cannot register evidence unit without evidence_id and document_id.")
        self.evidence_units[unit.evidence_id] = unit
        self.known_document_ids.add(unit.document_id)

    def add_structured_rule(self, rule: StructuredRuleRecord, strict: bool = True) -> bool:
        """
        Validate and insert a StructuredRuleRecord into the trusted store.
        If provenance or schema validation fails, reject the record and log the reason.
        """
        valid, errors = validate_structured_rule_record(
            rule,
            known_document_ids=self.known_document_ids if self.known_document_ids else None,
            known_evidence_ids=set(self.evidence_units.keys()) if self.evidence_units else None,
        )
        if not valid:
            self.rejected_rules.append({"rule": rule.to_dict(), "errors": errors})
            if strict:
                raise ValueError(f"Rejected malformed/untrusted rule {rule.rule_id}: {errors}")
            return False

        self.trusted_rules[rule.rule_id] = rule
        self.evidence_to_rules.setdefault(rule.evidence_id, []).append(rule)
        self._detect_and_flag_conflicts()
        return True

    def _detect_and_flag_conflicts(self) -> None:
        """
        Check all trusted rules sharing the same (scheme, rule_parameter, season, crop_category,
        geography, policy_era). If two official records specify different maximum_rate values,
        preserve both records and mark conflict_flag=True on each.
        """
        groups: dict[tuple[Any, ...], list[StructuredRuleRecord]] = {}
        for r in self.trusted_rules.values():
            key = (
                r.scheme,
                r.rule_parameter,
                r.season,
                r.crop_category,
                r.geography,
                r.policy_era,
            )
            groups.setdefault(key, []).append(r)

        for _, group_rules in groups.items():
            if len(group_rules) < 2:
                continue
            distinct_rates = {round(gr.maximum_rate, 6) for gr in group_rules}
            if len(distinct_rates) > 1:
                all_ids = [gr.rule_id for gr in group_rules]
                for gr in group_rules:
                    gr.conflict_flag = True
                    gr.conflicting_rule_ids = [rid for rid in all_ids if rid != gr.rule_id]

    def get_evidence_unit(self, evidence_id: str) -> ExtractedEvidenceUnit | None:
        return self.evidence_units.get(evidence_id)

    def get_rules_for_evidence(self, evidence_id: str) -> list[StructuredRuleRecord]:
        return list(self.evidence_to_rules.get(evidence_id, []))

    def has_evidence_id(self, evidence_id: str) -> bool:
        return evidence_id in self.evidence_units


